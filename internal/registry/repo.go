// Package registry is the registry of enrolled runners: which (org_id,
// runner_id) pairs exist, what certificate serial and expiry each currently
// holds, and whether it has been revoked. ADR-001 §3.2 ("Registration"),
// threat model §2.3 (S, E).
//
// This package holds no key material and no dependency on
// internal/builtin/sealer — a runner's certificate is public key material,
// not a secret, so it needs no envelope the way internal/builtin/orgpki's CA
// and job-signing private keys do. It is deliberately a sibling of
// internal/runner, not a subpackage — internal/api (which must wire the
// admin enrollment/revocation HTTP routes) cannot import internal/runner or
// internal/builtin per the zone-internals depguard rule, and this registry
// carries nothing that rule protects.
package registry

import (
	"context"
	"crypto/ecdh"
	"encoding/json"
	"errors"
	"fmt"
	"time"

	"github.com/entire-vc/evc-keep/internal/enrolltoken"
	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

var (
	// ErrRunnerRejected is the one error [Repo.CheckActive] ever returns for
	// a caller-facing failure — mirrors internal/enrolltoken.ErrTokenRejected:
	// an unknown runner_id, a wrong org, a revoked runner and a stale
	// (already-rotated) certificate serial all look identical to the runner
	// presenting the certificate, so the failure is never an oracle for
	// which of those it was (card's red-run test #3).
	ErrRunnerRejected = errors.New("registry: runner rejected")

	// ErrRunnerUnknown is returned by [Repo.Revoke] and [Repo.UpdateCert]
	// for "no such runner in this organization" and "already revoked" alike
	// — mirrors internal/identity.Repo.Revoke's ErrTokenUnknown: an admin
	// revoking a runner_id from another organization sees the same result
	// as revoking one that never existed.
	ErrRunnerUnknown       = errors.New("registry: runner unknown")
	ErrInvalidDeliveryKey  = errors.New("registry: invalid delivery public key")
	ErrDeliveryUnavailable = errors.New("registry: delivery unavailable")
)

// Enrollment binds public delivery material and administrator-asserted host
// attributes to a new runner. Zero values represent a legacy enrollment.
type Enrollment struct {
	HPKEPublicKey []byte
	HostAttrs     *enrolltoken.HostAttrs
}

// ValidateDeliveryPublicKey rejects malformed and low-order X25519 points
// before a one-time enrollment token is consumed.
func ValidateDeliveryPublicKey(public []byte) error {
	peer, err := ecdh.X25519().NewPublicKey(public)
	if err != nil {
		return ErrInvalidDeliveryKey
	}
	var scalar [32]byte
	scalar[0] = 1
	probe, err := ecdh.X25519().NewPrivateKey(scalar[:])
	if err != nil {
		return ErrInvalidDeliveryKey
	}
	if _, err := probe.ECDH(peer); err != nil {
		return ErrInvalidDeliveryKey
	}
	return nil
}

// DeliveryTrust is the server's org-scoped view of a runner's delivery key
// and administrator assertions. AttrsKnown=false is a legacy registration.
type DeliveryTrust struct {
	HPKEPublicKey []byte
	UIDShared     bool
	HostLabels    map[string]string
	AttrsKnown    bool
}

func (d DeliveryTrust) EligibleForProd() bool { return d.AttrsKnown && !d.UIDShared }

// Repo is runner-registry storage: a thin layer over the runners table.
type Repo struct {
	db *pgxpool.Pool
}

// NewRepo wraps an already-open pool (see internal/store.Open) as a Repo.
func NewRepo(db *pgxpool.Pool) *Repo {
	return &Repo{db: db}
}

// Create registers a freshly enrolled runner. runnerID is generated by the
// caller (internal/api's enroll handler) fresh at enrollment time — an
// enrollment token ([internal/enrolltoken.Redeemed]) carries only OrgID, no
// runner identity, so there is nothing to derive it from.
func (r *Repo) Create(ctx context.Context, orgID, runnerID uuid.UUID, host, certSerial string, notAfter time.Time) error {
	return create(ctx, r.db, orgID, runnerID, host, certSerial, notAfter, Enrollment{})
}

// CreateEnrolled stores a new runner with optional delivery trust.
func (r *Repo) CreateEnrolled(ctx context.Context, orgID, runnerID uuid.UUID, host, certSerial string, notAfter time.Time, enrollment Enrollment) error {
	return create(ctx, r.db, orgID, runnerID, host, certSerial, notAfter, enrollment)
}

func create(ctx context.Context, db execer, orgID, runnerID uuid.UUID, host, certSerial string, notAfter time.Time, enrollment Enrollment) error {
	if enrollment.HPKEPublicKey != nil {
		if err := ValidateDeliveryPublicKey(enrollment.HPKEPublicKey); err != nil {
			return err
		}
	}
	var uidShared *bool
	var labelsJSON []byte
	var source *string
	if enrollment.HostAttrs != nil {
		if err := enrollment.HostAttrs.Validate(); err != nil {
			return err
		}
		uidShared = enrollment.HostAttrs.UIDShared
		var err error
		labels := enrollment.HostAttrs.Labels
		if labels == nil {
			labels = map[string]string{}
		}
		labelsJSON, err = json.Marshal(labels)
		if err != nil {
			return enrolltoken.ErrInvalidHostAttrs
		}
		s := "enroll_token"
		source = &s
	}
	_, err := db.Exec(ctx,
		`INSERT INTO runners (id, org_id, host, cert_serial, cert_not_after, hpke_public_key, uid_shared, host_labels, attrs_source)
		 VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9)`,
		runnerID, orgID, host, certSerial, notAfter, enrollment.HPKEPublicKey, uidShared, labelsJSON, source)
	if err != nil {
		return fmt.Errorf("registry: create runner: %w", err)
	}
	return nil
}

// GetDeliveryTrust never reads a request-supplied key or host attribute.
// Cross-org, revoked, expired and keyless runners share one refusal.
func (r *Repo) GetDeliveryTrust(ctx context.Context, orgID, runnerID uuid.UUID) (DeliveryTrust, error) {
	return scanDeliveryTrust(r.db.QueryRow(ctx, `SELECT hpke_public_key, uid_shared, host_labels, attrs_source
		FROM runners WHERE id = $1 AND org_id = $2 AND revoked_at IS NULL AND cert_not_after > now()`,
		runnerID, orgID))
}

// GetDeliveryTrustTx locks the organization before the runner so deployment
// admission can hold a stable, trusted snapshot through its own transaction.
func (r *Repo) GetDeliveryTrustTx(ctx context.Context, tx pgx.Tx, orgID, runnerID uuid.UUID) (DeliveryTrust, error) {
	var lockedOrg uuid.UUID
	if err := tx.QueryRow(ctx, `SELECT id FROM organizations WHERE id = $1 FOR UPDATE`, orgID).Scan(&lockedOrg); err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return DeliveryTrust{}, ErrDeliveryUnavailable
		}
		return DeliveryTrust{}, fmt.Errorf("registry: lock organization: %w", err)
	}
	return scanDeliveryTrust(tx.QueryRow(ctx, `SELECT hpke_public_key, uid_shared, host_labels, attrs_source
		FROM runners WHERE id = $1 AND org_id = $2 AND revoked_at IS NULL AND cert_not_after > now() FOR UPDATE`,
		runnerID, orgID))
}

func scanDeliveryTrust(row pgx.Row) (DeliveryTrust, error) {
	var public []byte
	var uidShared *bool
	var labelsJSON []byte
	var source *string
	err := row.Scan(&public, &uidShared, &labelsJSON, &source)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return DeliveryTrust{}, ErrDeliveryUnavailable
		}
		return DeliveryTrust{}, fmt.Errorf("registry: delivery lookup: %w", err)
	}
	if ValidateDeliveryPublicKey(public) != nil {
		return DeliveryTrust{}, ErrDeliveryUnavailable
	}
	d := DeliveryTrust{HPKEPublicKey: public, HostLabels: map[string]string{}}
	if source != nil {
		if *source != "enroll_token" || uidShared == nil || json.Unmarshal(labelsJSON, &d.HostLabels) != nil {
			return DeliveryTrust{}, ErrDeliveryUnavailable
		}
		if err := (enrolltoken.HostAttrs{UIDShared: uidShared, Labels: d.HostLabels}).Validate(); err != nil {
			return DeliveryTrust{}, ErrDeliveryUnavailable
		}
		d.AttrsKnown = true
		d.UIDShared = *uidShared
	}
	return d, nil
}

// CheckActive reports whether (orgID, runnerID) names a runner that is not
// revoked and whose current certificate serial matches certSerial — the
// check internal/mtls.RequireMTLS makes on every mTLS request, after
// the certificate has already verified against the org's CA. Any mismatch
// (unknown runner, wrong org, revoked, stale serial from a certificate
// issued before the last renewal) returns the single [ErrRunnerRejected].
func (r *Repo) CheckActive(ctx context.Context, orgID, runnerID uuid.UUID, certSerial string) error {
	var revoked bool
	var serial string
	err := r.db.QueryRow(ctx,
		`SELECT revoked_at IS NOT NULL, cert_serial FROM runners WHERE id = $1 AND org_id = $2`,
		runnerID, orgID).Scan(&revoked, &serial)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return ErrRunnerRejected
		}
		return fmt.Errorf("registry: check active: %w", err)
	}
	if revoked || serial != certSerial {
		return ErrRunnerRejected
	}
	return nil
}

// UpdateCert records a renewed certificate for an existing, non-revoked
// runner (POST /runners/renew, over the runner's current still-valid mTLS
// connection). A revoked or unknown (org_id, runner_id) is refused with
// [ErrRunnerUnknown], not silently accepted. The update compares the current
// serial with the authenticated certificate, so overlapping renewals cannot
// both succeed and invalidate an already successful response.
func (r *Repo) UpdateCert(ctx context.Context, orgID, runnerID uuid.UUID, expectedSerial, newSerial string, newNotAfter time.Time) error {
	return updateCert(ctx, r.db, orgID, runnerID, expectedSerial, newSerial, newNotAfter)
}

func updateCert(ctx context.Context, db execer, orgID, runnerID uuid.UUID, expectedSerial, newSerial string, newNotAfter time.Time) error {
	tag, err := db.Exec(ctx,
		`UPDATE runners SET cert_serial = $1, cert_not_after = $2
		 WHERE id = $3 AND org_id = $4 AND revoked_at IS NULL AND cert_serial = $5`,
		newSerial, newNotAfter, runnerID, orgID, expectedSerial)
	if err != nil {
		return fmt.Errorf("registry: update cert: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return ErrRunnerUnknown
	}
	return nil
}

// Revoke marks a runner revoked (keep runner revoke <runner_id>). Org-scoped
// and idempotent: a runner from another organization, one that never
// existed, and one already revoked all return the same [ErrRunnerUnknown]
// — mirrors internal/identity.Repo.Revoke exactly, for the same reason.
func (r *Repo) Revoke(ctx context.Context, orgID, runnerID uuid.UUID) error {
	now := time.Now().UTC()
	tag, err := r.db.Exec(ctx,
		`UPDATE runners SET revoked_at = $1 WHERE id = $2 AND org_id = $3 AND revoked_at IS NULL`,
		now, runnerID, orgID)
	if err != nil {
		return fmt.Errorf("registry: revoke: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return ErrRunnerUnknown
	}
	return nil
}

// execer keeps the same org/serial guards for transactional and ordinary writes.
type execer interface {
	Exec(context.Context, string, ...any) (pgconn.CommandTag, error)
}

// CreateAudited commits registration and its journal callback together.
func (r *Repo) CreateAudited(ctx context.Context, orgID, runnerID uuid.UUID, host, serial string, expiry time.Time, appendAudit func(pgx.Tx) error) error {
	return r.CreateEnrolledAudited(ctx, orgID, runnerID, host, serial, expiry, Enrollment{}, appendAudit)
}

// CreateEnrolledAudited commits enrollment and its audit record together.
func (r *Repo) CreateEnrolledAudited(ctx context.Context, orgID, runnerID uuid.UUID, host, serial string, expiry time.Time, enrollment Enrollment, appendAudit func(pgx.Tx) error) error {
	return r.mutateAudited(ctx, func(tx pgx.Tx) error { return create(ctx, tx, orgID, runnerID, host, serial, expiry, enrollment) }, appendAudit)
}

// UpdateCertAudited commits a guarded serial change and its journal together.
func (r *Repo) UpdateCertAudited(ctx context.Context, orgID, runnerID uuid.UUID, oldSerial, newSerial string, expiry time.Time, appendAudit func(pgx.Tx) error) error {
	return r.mutateAudited(ctx, func(tx pgx.Tx) error { return updateCert(ctx, tx, orgID, runnerID, oldSerial, newSerial, expiry) }, appendAudit)
}

func (r *Repo) mutateAudited(ctx context.Context, mutation, appendAudit func(pgx.Tx) error) error {
	tx, err := r.db.Begin(ctx)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback(ctx) }()
	if err := mutation(tx); err != nil {
		return err
	}
	if err := appendAudit(tx); err != nil {
		return err
	}
	return tx.Commit(ctx)
}
