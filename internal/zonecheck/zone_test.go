// Package zonecheck pins the exported API of the plaintext zone: the
// packages allowed to read a secret's bytes (see .golangci.yml, rule
// expose-callers). Lint keeps secret.Expose inside the zone, but zone code
// can still hand plaintext access out: `var Unseal = secret.Expose`, a
// wrapper returning the bytes, a method that type-asserts an `any`, a
// closure in an unexported field. No rule can tell that from a legitimate
// zone API, and any filter on "types that look sensitive" is defeated by
// erasing the type. So nothing is filtered: every exported function,
// variable and method, and every named type with its full structure, is
// listed in plaintext_api.txt. Any change to that surface fails this test
// until the list changes in the same merge request, where a reviewer sees it
// and decides whether it leaks.
//
// Regenerate after an intended change: go test ./internal/zonecheck -update
package zonecheck

import (
	"flag"
	"go/build"
	"go/importer"
	"go/token"
	"go/types"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"testing"
)

const module = "github.com/entire-vc/evc-keep"

// zoneRoots must match the expose-callers exclusion in .golangci.yml.
var zoneRoots = []string{
	"pkg/secret", "pkg/fingerprint", "pkg/provider",
	"internal/builtin", "internal/runner", "internal/targets",
}

var update = flag.Bool("update", false, "rewrite plaintext_api.txt from the current code")

const listFile = "plaintext_api.txt"

const header = `# Exported API of the plaintext zone. Generated by
# go test ./internal/zonecheck -update; see zone_test.go.
# Every changed line here is a change to code that can read plaintext:
# review each one for a way to hand the bytes out.
`

func TestPlaintextAPI(t *testing.T) {
	// Trimmed test binaries can have no embedded GOROOT. The source
	// importer also needs the build context initialized before importing.
	var goroot string
	if out, err := exec.Command("go", "env", "GOROOT").Output(); err == nil {
		goroot = strings.TrimSpace(string(out))
	}
	if goroot == "" {
		goroot = runtime.GOROOT() //nolint:staticcheck // SA1019: only a fallback when the go tool is unavailable.
	}
	if goroot == "" {
		t.Fatal("cannot determine GOROOT for the source importer")
	}
	t.Setenv("GOROOT", goroot)
	previous := build.Default.GOROOT
	build.Default.GOROOT = goroot
	t.Cleanup(func() { build.Default.GOROOT = previous })

	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	got := surface(t, root)

	// Positive control: if the walker cannot see the one entry that must
	// exist, an empty diff below would prove nothing.
	if !contains(got, "pkg/secret.Expose: func(v secret.Value, fn func([]byte))") {
		t.Fatalf("surface walker did not find secret.Expose; it is broken, not the code clean:\n%s", strings.Join(got, "\n"))
	}

	if *update {
		if err := os.WriteFile(listFile, []byte(header+strings.Join(got, "\n")+"\n"), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	raw, err := os.ReadFile(listFile)
	if err != nil {
		t.Fatalf("read %s: %v", listFile, err)
	}
	var want []string
	for _, l := range strings.Split(string(raw), "\n") {
		if l != "" && !strings.HasPrefix(l, "#") {
			want = append(want, l)
		}
	}
	added, removed := diff(want, got)
	for _, l := range added {
		t.Errorf("new plaintext-zone export, not in %s:\n\t%s", listFile, l)
	}
	for _, l := range removed {
		t.Errorf("listed in %s but gone from the code:\n\t%s", listFile, l)
	}
	if len(added)+len(removed) > 0 {
		t.Log("if the change is intended: go test ./internal/zonecheck -update, and call it out in the merge request")
	}
}

func surface(t *testing.T, root string) []string {
	t.Helper()
	fset := token.NewFileSet()
	imp := importer.ForCompiler(fset, "source", nil)
	var out []string
	for _, dir := range zonePackages(t, root) {
		p, err := imp.Import(module + "/" + dir)
		if err != nil {
			t.Fatalf("import %s: %v", dir, err)
		}
		q := func(o *types.Package) string { return o.Name() }
		add := func(name string, typ types.Type) {
			out = append(out, dir+"."+name+": "+types.TypeString(typ, q))
		}
		sc := p.Scope()
		for _, name := range sc.Names() {
			obj := sc.Lookup(name)
			switch o := obj.(type) {
			case *types.Func, *types.Var:
				if o.Exported() {
					add(name, o.Type())
				}
			case *types.TypeName:
				named, ok := o.Type().(*types.Named)
				if !ok {
					continue
				}
				// Unexported types too: a value of one can escape through an
				// exported function, and its exported methods are then
				// callable. Their structure is listed with unexported fields,
				// so a closure hidden in a field changes the line.
				if o.Exported() {
					add(name, named.Underlying())
				}
				for i := 0; i < named.NumMethods(); i++ {
					if m := named.Method(i); m.Exported() {
						add(name+"."+m.Name(), m.Type())
					}
				}
			}
		}
	}
	sort.Strings(out)
	return out
}

// zonePackages lists every directory under the zone roots that holds a
// non-test Go file.
func zonePackages(t *testing.T, root string) []string {
	t.Helper()
	seen := map[string]bool{}
	for _, r := range zoneRoots {
		base := filepath.Join(root, r)
		if _, err := os.Stat(base); os.IsNotExist(err) {
			continue
		}
		err := filepath.WalkDir(base, func(p string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() && d.Name() == "testdata" {
				return filepath.SkipDir
			}
			if !d.IsDir() && strings.HasSuffix(p, ".go") && !strings.HasSuffix(p, "_test.go") {
				rel, _ := filepath.Rel(root, filepath.Dir(p))
				seen[filepath.ToSlash(rel)] = true
			}
			return nil
		})
		if err != nil {
			t.Fatal(err)
		}
	}
	var dirs []string
	for d := range seen {
		dirs = append(dirs, d)
	}
	sort.Strings(dirs)
	return dirs
}

func diff(want, got []string) (added, removed []string) {
	w, g := map[string]bool{}, map[string]bool{}
	for _, l := range want {
		w[l] = true
	}
	for _, l := range got {
		g[l] = true
		if !w[l] {
			added = append(added, l)
		}
	}
	for _, l := range want {
		if !g[l] {
			removed = append(removed, l)
		}
	}
	return added, removed
}

func contains(list []string, s string) bool {
	for _, l := range list {
		if l == s {
			return true
		}
	}
	return false
}
