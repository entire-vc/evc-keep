#!/usr/bin/env python3
"""Generate full tests unless an MR changes only existing, regular docs."""
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
# Explicit files, not a suffix/glob: new documentation paths get full CI
# until this list is deliberately reviewed. Additions, deletes, renames,
# symlinks and executable-bit changes also require the full checks.
DOCS = frozenset({"README.md", "CONTRIBUTING.md", "SECURITY.md",
                  "docs/carrier-discovery.md"})


def docs_only(changes):
    return bool(changes) and all(status == "M" and name in DOCS for status, name in changes)


def can_skip(context):
    return (context.get("CI_PIPELINE_SOURCE") == "merge_request_event"
            and not context.get("KEEP_FULL_CI")
            and context.get("CI_COMMIT_BRANCH") != context.get("CI_DEFAULT_BRANCH"))


def read_diff(base, head, root=ROOT):
    subprocess.run(["git", "merge-base", "--is-ancestor", base, head], cwd=root, check=True)
    # Disable rename detection: a rename becomes D+A and cannot be skipped.
    raw = subprocess.check_output(
        ["git", "diff", "--raw", "-z", "--no-renames", base, head, "--"], cwd=root)
    fields = raw.split(b"\0")
    if fields.pop() != b"" or len(fields) % 2:
        raise ValueError("malformed diff")
    changes = []
    for header, name in zip(fields[::2], fields[1::2]):
        parts = header.split()
        if len(parts) != 5 or not parts[0].startswith(b":"):
            raise ValueError("malformed raw diff record")
        status = parts[4].decode("ascii")
        if parts[0] != b":100644" or parts[1] != b"100644":
            status = "mode-change"
        changes.append((status, name.decode("utf-8", errors="surrogateescape")))
    return changes


def render(skip, main):
    policy = "none" if main else "interruptible"
    header = ("# Generated by scripts/generate-test-pipeline.py.\n"
              f"workflow:\n  auto_cancel:\n    on_new_commit: {policy}\n"
              "  rules:\n    - when: always\n"
              "stages: [test]\n"
              "default:\n  tags: [docker]\n  interruptible: true\n"
              "  retry:\n    max: 2\n"
              "    when: [runner_system_failure, scheduler_failure, api_failure]\n"
              'variables:\n  GOFLAGS: "-buildvcs=false"\n')
    if skip:
        return header + ("docs-only:\n  stage: test\n  image: alpine:3.22\n"
                         "  rules:\n    - when: on_success\n"
                         "  script:\n    - echo 'Existing regular documentation only; full tests omitted'\n")
    return header + (ROOT / ".gitlab/ci/full-tests.yml").read_text()


def main():
    context = os.environ
    skip = False
    if can_skip(context):
        base = context.get("CI_MERGE_REQUEST_DIFF_BASE_SHA", "")
        head = context.get("CI_COMMIT_SHA", "")
        try:
            if not all(re.fullmatch(r"[0-9a-f]{40}", ref) and ref != "0" * 40
                       for ref in (base, head)):
                raise ValueError("missing or invalid diff SHA")
            skip = docs_only(read_diff(base, head))
        except (ValueError, subprocess.CalledProcessError):
            # An unavailable/ambiguous diff runs the full tests.
            print("Diff not proven docs-only; selecting full tests", file=sys.stderr)
    is_main = (bool(context.get("CI_DEFAULT_BRANCH"))
               and context.get("CI_COMMIT_BRANCH") == context.get("CI_DEFAULT_BRANCH"))
    output = Path(sys.argv[1])
    output.write_text(render(skip, is_main))
    print("Selected " + ("docs-only" if skip else "full test matrix and intake-browser"))


if __name__ == "__main__":
    main()
